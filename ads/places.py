"""Город и район для регионов кроме Гоа (в Гоа — только посёлок, города нет).

GPT присылает city и village (район внутри города), но путает: пишет район без города,
город вместо района. split_place() приводит ответ к виду (город, район) по известным спискам.
Используется сборщиком и миграцией 0025 (заполнение города у старых объявлений).
"""

# Регион → город → его районы. Первый город региона — главный (в меню первым).
DISTRICTS = {
    "am": {
        "Ереван": ["Аван", "Арабкир", "Ачапняк", "Давташен", "Кентрон", "Канакер-Зейтун",
                   "Малатия-Себастия", "Нор-Норк", "Норк-Мараш", "Нубарашен", "Шенгавит", "Эребуни"],
    },
    "ge": {
        "Тбилиси": ["Ваке", "Глдани", "Дидубе", "Исани", "Крцаниси", "Мтацминда", "Надзаладеви",
                    "Сабуртало", "Самгори", "Чугурети"],
        "Батуми": ["Старый Батуми", "Новый бульвар", "Махинджаури", "Гонио"],
    },
}

# Микрорайоны и другие написания → район (город определится по району)
ALIASES = {
    "ge": {"Варкетили": "Самгори", "Сололаки": "Мтацминда", "Вера": "Мтацминда",
           "Ортачала": "Крцаниси", "Авлабари": "Исани", "Дигоми": "Сабуртало",
           "Диди Дигоми": "Сабуртало", "Багеби": "Ваке", "Лиси": "Ваке", "Цхнети": "Ваке", "Старый город": "Старый Батуми"},
}


def main_city(region: str) -> str | None:
    return next(iter(DISTRICTS.get(region, {})), None)


def split_place(region: str, city: str | None, village: str | None) -> tuple[str | None, str | None]:
    """(город, район). Район известного города → его город; название города в районе → город без района;
    неизвестное место без города (Дилижан, Мцхета) — это город."""
    if region not in DISTRICTS:
        return None, village
    city = (city or "").strip() or None
    village = (village or "").strip() or None
    village = ALIASES.get(region, {}).get(village, village)
    for c, districts in DISTRICTS[region].items():
        if village in districts:
            return c, village
    if village and (village == city or village in DISTRICTS[region] or not city):
        return village, None
    if city in DISTRICTS[region]:
        return city, None   # незнакомый «район» большого города — в меню районов не пускаем
    return city, village
